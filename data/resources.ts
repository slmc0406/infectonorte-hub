export function getAllPublicResources() {
  return resources.filter((r) => r.visibility === 'publico' || r.visibility === 'general_infectonorte');
}

export function getResourceBySlug(slug: string) {
  return resources.find((r) => r.slug === slug) ?? null;
}

export function getResourcesForInstitution(institutionId: string) {
  return resources.filter(
    (r) =>
      r.visibility === 'publico' ||
      r.visibility === 'general_infectonorte' ||
      (r.visibility === 'exclusivo' && r.ownerInstitutionId === institutionId)
    // 'instituciones_seleccionadas' se resolvería contra institution_resources — no usado en el MVP demo.
  );
}

export function getRelatedResources(resource: Resource) {
  return resource.relatedResourceIds.map((id) => resources.find((r) => r.id === id)).filter(Boolean) as Resource[];
}

export function getAllResourcesAdmin() {
  return resources;
}

export function getResourceById(id: string) {
  return resources.find((r) => r.id === id) ?? null;
}

// Mutaciones en memoria para el panel administrativo del MVP demo — en
// producción son INSERT/UPDATE a `resources` + una fila nueva en
// `resource_versions` por cada publicación (ver docs, modelo de datos).
export function createResource(input: Partial<Resource> & { title: string; slug: string; type: Resource['type']; typePath: string }): Resource {
  const now = new Date().toISOString();
  const resource: Resource = {
    id: `res-${Date.now()}`,
    slug: input.slug,
    title: input.title,
    summary: input.summary ?? '',
    description: input.description ?? '',
    keyPoints: input.keyPoints ?? [],
    type: input.type,
    typePath: input.typePath,
    status: input.status ?? 'borrador',
    visibility: input.visibility ?? 'general_infectonorte',
    ownerInstitutionId: input.ownerInstitutionId,
    parentResourceId: input.parentResourceId,
    areas: input.areas ?? [],
    populations: input.populations ?? [],
    syndromes: input.syndromes ?? [],
    tags: input.tags ?? [],
    authors: input.authors ?? [],
    institutionName: input.institutionName,
    references: input.references ?? [],
    relatedResourceIds: input.relatedResourceIds ?? [],
    version: input.version ?? '1.0',
    createdAt: now,
    publishedAt: input.status === 'vigente' ? now : (input.publishedAt ?? now),
    lastReviewedAt: input.lastReviewedAt ?? now,
    nextReviewAt: input.nextReviewAt ?? now,
    coverImage: input.coverImage,
    fileUrl: input.fileUrl ?? '#',
    isDemo: false,
    presentation: input.presentation,
    views: 0,
    downloads: 0,
  };
  resources.push(resource);
  return resource;
}

export function updateResource(id: string, patch: Partial<Resource>): Resource | null {
  const resource = getResourceById(id);
  if (!resource) return null;
  Object.assign(resource, patch);
  return resource;
}
